"""
50_assemble.py -- assemble the manuscript from its parts.

Order is fixed here so that the file can be regenerated byte-for-byte from the parts
plus the tables. Nothing in this script computes; it only concatenates.
"""
from __future__ import annotations

import os
import re

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MS = os.path.join(HERE, "manuscript")
TAB = os.path.join(MS, "tables")


def read(*parts: str) -> str:
    with open(os.path.join(*parts), encoding="utf-8") as fh:
        return fh.read().strip()


def kb(path: str) -> str:
    """Size of an additional file as the submission system will report it."""
    return f"{max(1, round(os.path.getsize(path) / 1024)):,}"



def declarations() -> str:
    return read(MS, "declarations.md") if os.path.exists(
        os.path.join(MS, "declarations.md")) else ""


def discussion_with_failure() -> str:
    """The failure section reads inside the Discussion, as 4.6, ahead of Limitations.

    It is kept in its own file because it is the part of the argument a reader is most
    likely to quote back at us, and a separate file makes it easy to find; at assembly
    time it is spliced in at the 4.7 marker rather than being appended after the
    Discussion, which is where it sat before the manuscript was put into the numbered
    scheme.
    """
    d = read(MS, "discussion.md")
    f = read(MS, "failure_and_coarsegraining.md")
    marker = "## 4.7 Limitations"
    if marker not in d:
        raise SystemExit(f"50_assemble: marker {marker!r} not found in discussion.md")
    head, tail = d.split(marker, 1)
    return head + f + "\n\n" + marker + tail


BODY = ["intro.md", "methods_full.md", "results_full.md",
        "failure_and_coarsegraining.md", "discussion.md"]


def word_count() -> int:
    """Main text only, in the sense a journal counts it.

    Introduction through Discussion, excluding display equations and inline result tables:
    those are counted as tables, and including them would inflate the figure a reader
    checks against the manuscript.
    """
    total = 0
    for p in BODY:
        kept = []
        for line in read(MS, p).splitlines():
            t = line.strip()
            if t.startswith("|") or re.match(r"^(d[ACER]/dt|R_p =|L =|    )", t):
                continue
            kept.append(line)
        total += len(re.sub(r"[#*_>`|]", " ", "\n".join(kept)).split())
    return total


def main() -> int:
    # Journal order, matching the group's previous JTM paper: title page, abstract,
    # 1. Introduction, 2. Methods, 3. Results, 4. Discussion (including the failure
    # section and the run-in Conclusions), abbreviations, declarations, additional
    # files, 5. Tables, 6. Figure legends, 7. References.
    parts = [
        FRONT,
        read(MS, "abstract.md"),
        "\n---\n",
        read(MS, "intro.md"),
        "\n---\n",
        read(MS, "methods_full.md"),
        "\n---\n",
        read(MS, "results_full.md"),
        "\n---\n",
        discussion_with_failure(),
        "\n---\n",
        read(MS, "abbreviations.md"),
        "\n---\n",
        read(MS, "declarations.md"),
        "\n---\n",
        "# Additional files\n\n",
        f"**Additional file 1. Supplementary tables S1\u2013S13.** Thirteen tables carrying the\n"
        "substance-key normalisation, the exposure-role sensitivity, the EBGM hyperparameters, the\n"
        "endothelial quality gate, the gene modules, the all-pairs proximity statistics, the\n"
        "pre-2018 coding sensitivity, the leave-one-product-out prediction, the EudraVigilance\n"
        "replication, the reporting strata, the severity proxy, the model parameters and the\n"
        f"positive control for the network null.\n",
        "**Additional file 2. RECORD/STROBE checklist.** The completed checklist for this\n"
        "case-level pharmacovigilance analysis, item by item against the section of the manuscript\n"
        f"where each item is addressed.",
        "\n---\n",
        "# 5. Tables\n\n",
        read(TAB, "table1_products.md"),
        "\n\n",
        read(TAB, "table2_specifications.md"),
        "\n\n",
        read(TAB, "table3_decidability.md"),
        "\n---\n",
        read(MS, "figure_legends.md"),
        "\n---\n",
        read(MS, "references.md"),
        "\n---\n",
        "\n",
    ]
    text = "\n".join(p for p in parts if p)
    out = os.path.join(MS, "manuscript.md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(text)

    words = len(re.findall(r"\b[\w'’-]+\b", text))
    print(f"written {out}  ({len(text):,} chars, ~{words:,} words incl. tables)")
    print(f"main text (Introduction through Discussion): {word_count():,} words")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
